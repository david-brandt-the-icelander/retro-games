/** Parse an 8-row "#." picture into 8 bytes (bit 7 = leftmost pixel). */
export function parseGlyph(picture: string): number[] {
  const rows = picture.trim().split(/\s+/);
  if (rows.length !== 8 || rows.some((r) => !/^[#.]{8}$/.test(r))) throw new Error(`bad glyph: ${picture}`);
  return rows.map((r) => [...r].reduce((b, c) => (b << 1) | (c === "#" ? 1 : 0), 0));
}

const FONT = new Map<string, number[]>(Object.entries(GLYPHS).map(([ch, pic]) => [ch, parseGlyph(pic)]));
const UNKNOWN = parseGlyph(GLYPHS["?"]);

/** The 8 bytes for a character; unknown characters draw as '?'. */
export const glyph = (ch: string): number[] => FONT.get(ch) ?? UNKNOWN;
export const hasGlyph = (ch: string): boolean => FONT.has(ch);
export const CHARSET = [...FONT.keys()];
